using Google.Protobuf.Reflection;

namespace EndfieldLogs.Runtime.Capture;

public sealed record CaptureRecordingPaths(string SessionPath, string TracePath);
public sealed record SessionPreviousVolume(int Volume, string File);
public sealed record SessionVolumeHeader(string RecordingId, string SessionId, int Volume,
    SessionPreviousVolume? PreviousVolume, long EventOffset, string TraceRecordingId, int TraceVolume,
    [property: JsonPropertyName("timezone_offset_minutes")] int TimeZoneOffsetMinutes,
    string Type = "session_volume", int SchemaVersion = 1);

/// <summary>Session NDJSON, opt-in replay diagnostics and the uploader-compatible trace status sidecar.</summary>
public sealed class CaptureArtifacts(TraceRecording trace, string gameExecutable, string? logDirectory,
    string? debugDirectory = null, Action<string, Exception?>? diagnostic = null) : IDisposable
{
    private static readonly UTF8Encoding Utf8 = new(false, true);
    private readonly Dictionary<(string Top, string Bucket), int> counters = [];
    private readonly Dictionary<string, IReadOnlyDictionary<string, string>> schemas = new(StringComparer.Ordinal);
    private StreamWriter? events;
    private string? sessionId, debugSession;
    private string? activeEventFile;
    private int eventVolume;
    private long eventCount;
    private string? recordingId;
    private readonly RecordingContext context = new();
    private TraceRecording? disk;
    public bool Recording => disk is not null;
    public string? TraceFilePath => disk?.FilePath;
    public string? EventFilePath { get; private set; }
    public string? StatusFilePath => TraceFilePath is { } path ? path + ".status.json" : null;
    public long WriteErrors { get; private set; }
    public bool IsWriting(string path) => disk?.IsWriting(path) == true || Volatile.Read(ref activeEventFile) is { } active
        && string.Equals(active, Path.GetFullPath(path), StringComparison.OrdinalIgnoreCase);

    public CaptureRecordingPaths? SetRecording(bool active)
    {
        if (active == Recording) return active ? new(EventFilePath!, TraceFilePath!) : null;
        if (!active)
        {
            trace.FlushPending();
            var previous = disk; disk = null;
            try { previous?.CloseFile(); }
            finally
            {
                try { events?.Dispose(); }
                finally { events = null; EventFilePath = null; Volatile.Write(ref activeEventFile, null); }
            }
            return null;
        }
        if (logDirectory is null) throw new InvalidOperationException("未配置日志目录");
        trace.FlushPending();
        disk = trace.NewFileRecording(logDirectory);
        try
        {
            var id = recordingId = Guid.NewGuid().ToString("N");
            var directory = Path.GetDirectoryName(disk.FilePath!)!;
            EventFilePath = Path.Combine(directory, "session_" + id + ".ndjson");
            events = new(new FileStream(EventFilePath, FileMode.CreateNew, FileAccess.Write, FileShare.Read), Utf8)
                { AutoFlush = true, NewLine = "\n" };
            eventVolume = 1; eventCount = 0;
            WriteVolumeHeader(events, 1, null, id);
            Volatile.Write(ref activeEventFile, EventFilePath);
            foreach (var value in context.Snapshot()) { disk.Handle(value); WriteRecordedEvent(value); }
            disk.FlushPending();
            return new(EventFilePath, disk.FilePath!);
        }
        catch { SetRecording(false); throw; }
    }

    public void BeginSession(string id)
    {
        CloseSession();
        // Session identifiers are generated by the service, never filesystem fragments from a packet.
        if (id.Length == 0 || id.Any(value => !char.IsAsciiLetterOrDigit(value) && value is not '-' and not '_'))
            throw new ArgumentException("Invalid capture session identifier", nameof(id));
        sessionId = id;
        var day = DateTime.Now.ToString("yyyyMMdd", CultureInfo.InvariantCulture);
        if (debugDirectory is not null)
        {
            debugSession = Path.Combine(Path.GetFullPath(debugDirectory), day, "session_" + id);
            Directory.CreateDirectory(debugSession);
        }
    }

    public void WriteEvent(BattleLogEvent value)
    {
        context.Observe(value);
        WriteRecordedEvent(value);
    }
    private void WriteRecordedEvent(BattleLogEvent value)
    {
        if (events is null) return;
        try { events.WriteLine(TraceData.Json(TraceData.Value(value.ToPayload()))); eventCount++; }
        catch (IOException error) { WriteErrors++; diagnostic?.Invoke("战斗事件日志写入失败", error); }
    }
    public void WriteTraceEvents(IReadOnlyList<EndfieldLogs.Core.Tracing.TraceEvent> source) => disk?.AppendEvents(source);
    public void WriteTraceLine(string line) => disk?.AppendLine(line);

    private void WriteVolumeHeader(StreamWriter output, int volume, SessionPreviousVolume? previous, string? recordingId = null)
    {
        if (disk?.CurrentHeader is not { } header) return; // Existing legacy sessions remain readable unchanged.
        var id = recordingId ?? this.recordingId!;
        output.WriteLine(JsonContract.Serialize(new SessionVolumeHeader(id, id, volume,
            previous, eventCount, header.RecordingId, header.Volume, header.TimeZoneOffsetMinutes)));
    }

    /// <summary>The capture owner invokes this between complete business calls; no flow or analysis state changes.</summary>
    public CaptureRecordingPaths RotateRecording()
    {
        if (events is null || EventFilePath is null || disk?.CurrentHeader is null)
            throw new InvalidOperationException("请在 JSONL 抓包会话开始后新建记录");
        var nextVolume = checked(eventVolume + 1);
        var nextPath = Path.Combine(Path.GetDirectoryName(EventFilePath)!, $"session_{recordingId}_v{nextVolume:D3}.ndjson");
        // Reserve the paired session before changing either active writer. Trace rotation also reserves its next file first.
        StreamWriter? next = new(new FileStream(nextPath, FileMode.CreateNew, FileAccess.Write, FileShare.Read), Utf8)
            { AutoFlush = true, NewLine = "\n" };
        try
        {
            events.Flush();
            var nextTrace = disk.RotateVolume();
            WriteVolumeHeader(next, nextVolume, new(eventVolume, Path.GetFileName(EventFilePath)));
            var previous = events;
            events = next; next = null; EventFilePath = nextPath; eventVolume = nextVolume;
            Volatile.Write(ref activeEventFile, nextPath);
            previous.Dispose();
            return new(nextPath, nextTrace);
        }
        finally { next?.Dispose(); }
    }

    public void WriteMessage(DecodedMessage decoded, long timestampMs)
    {
        if (debugSession is null) return;
        if (!schemas.TryGetValue(decoded.ClassName, out var schema))
        {
            SortedDictionary<string, string> hashes = new(StringComparer.Ordinal);
            Stack<FileDescriptor> pending = new(); pending.Push(decoded.Message.Descriptor.File);
            while (pending.TryPop(out var file))
            {
                if (hashes.ContainsKey(file.Name)) continue;
                hashes[file.Name] = Convert.ToHexStringLower(SHA256.HashData(file.SerializedData.Span));
                foreach (var dependency in file.Dependencies) pending.Push(dependency);
            }
            schemas[decoded.ClassName] = schema = hashes;
        }
        object Message(bool numericEnums) => System.Text.Json.JsonSerializer.Deserialize<System.Text.Json.JsonElement>(
            new JsonFormatter(new JsonFormatter.Settings(true).WithPreserveProtoFieldNames(true)
                .WithFormatEnumsAsIntegers(numericEnums)).Format(decoded.Message));
        WriteDebug("proto", decoded.ClassName, timestampMs, decoded.Direction, new Dictionary<string, object?>
        {
            ["type"] = "debug_proto", ["session_id"] = sessionId, ["timestamp_ms"] = timestampMs,
            ["direction"] = decoded.Direction, ["class_name"] = decoded.ClassName, ["msg_id"] = decoded.MessageId,
            ["head"] = decoded.Head.ToPayload(), ["raw_body_format"] = "protobuf_body_after_decompression_and_reassembly",
            ["raw_body_size"] = decoded.RawBody.Length, ["raw_body_sha256"] = Convert.ToHexStringLower(SHA256.HashData(decoded.RawBody)),
            ["raw_body_base64"] = Convert.ToBase64String(decoded.RawBody), ["protobuf_schema_files_sha256"] = schema,
            ["message"] = Message(false), ["message_enum_ints"] = Message(true),
        });
    }

    public void WriteDebugRecord(Dictionary<string, object?> value)
    {
        if (debugSession is null) return;
        var type = value.GetValueOrDefault("type") as string;
        var bucket = type switch
        {
            "debug_frame_error" => "frame_error", "debug_decompression_error" => "decompression_error",
            "debug_protobuf_error" => "protobuf_error", "debug_session_head" => "session_head",
            "debug_tcp_gap" => "tcp_gap", "debug_multipack_pending" => "multipack_pending",
            "debug_multipack_incomplete" => "multipack_incomplete", _ => "undecoded_frame",
        };
        var timestamp = Convert.ToInt64(value.GetValueOrDefault("timestamp_ms") ?? 0, CultureInfo.InvariantCulture);
        WriteDebug("issues", bucket, timestamp, value.GetValueOrDefault("direction") as string ?? "na", value);
    }

    private void WriteDebug(string top, string bucket, long timestamp, string direction, object payload)
    {
        if (debugSession is null) return;
        if (bucket.Any(value => !char.IsAsciiLetterOrDigit(value) && value != '_'))
            throw new InvalidDataException("Invalid diagnostic category");
        direction = direction is "cs" or "sc" ? direction : "na";
        var key = (top, bucket); var index = counters.GetValueOrDefault(key) + 1; counters[key] = index;
        var directory = Path.Combine(debugSession, top, bucket); Directory.CreateDirectory(directory);
        var name = index.ToString("D6", CultureInfo.InvariantCulture) + "_" + timestamp.ToString(CultureInfo.InvariantCulture) + "_" + direction + ".json";
        File.WriteAllText(Path.Combine(directory, name), payload is Dictionary<string, object?> map
            && !map.ContainsKey("message") ? TraceData.Json(TraceData.Value(map)) : JsonContract.Serialize(payload), Utf8);
    }

    public Dictionary<string, object?> StatusPayload(CaptureRuntimeSnapshot snapshot, RuntimeMetrics metrics,
        IReadOnlyList<DeviceInfo> devices)
    {
        long? size = EventFilePath is { } path && File.Exists(path) ? new FileInfo(path).Length : null;
        var flow = snapshot.Flow.Flow;
        return new()
        {
            ["type"] = "status", ["schema_version"] = 1, ["state"] = snapshot.Flow.State,
            ["recording"] = Recording,
            ["game_exe"] = gameExecutable, ["session_id"] = snapshot.Flow.SessionId,
            ["active_flow"] = flow is null ? null : new { client = $"{flow.Client.Ip}:{flow.Client.Port}", server = $"{flow.Server.Ip}:{flow.Server.Port}" },
            ["session"] = snapshot.Flow.Session,
            ["log"] = new { dir = logDirectory, path = EventFilePath, size, write_errors = WriteErrors },
            ["capture_devices"] = devices.Select(device => new { device.Name, device.Description, ipv4_addrs = device.Ipv4Addresses }).ToArray(),
            ["metrics"] = new
            {
                packets_seen = snapshot.PacketsSeen, packets_dropped_queue = snapshot.QueueDrops,
                metrics.FramesDecoded, metrics.MessagesDecoded, metrics.DecompressionErrors,
                metrics.ProtobufDecodeErrors, metrics.OutboundEventsEmitted, metrics.WsBatchesSent,
            },
            ["pcap_stats"] = new { ps_recv = snapshot.Statistics.Received, ps_drop = snapshot.Statistics.Dropped, ps_ifdrop = snapshot.Statistics.InterfaceDropped },
            ["fatal_error"] = snapshot.Error is null ? null : new { task = snapshot.ErrorTask ?? "capture", type = snapshot.ErrorType ?? "CaptureError", message = snapshot.Error },
            ["updated_at_ms"] = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds(),
        };
    }

    public void WriteStatus(CaptureRuntimeSnapshot snapshot, RuntimeMetrics metrics, IReadOnlyList<DeviceInfo> devices, string? finalPath = null)
    {
        if ((finalPath ?? StatusFilePath) is not { } path) return;
        var temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            File.WriteAllText(temporary, JsonContract.Serialize(StatusPayload(snapshot, metrics, devices)), Utf8);
            File.Move(temporary, path, overwrite: true);
        }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException)
        { diagnostic?.Invoke("抓包状态文件写入失败", error); }
        finally
        {
            try { if (File.Exists(temporary)) File.Delete(temporary); }
            catch (Exception error) when (error is IOException or UnauthorizedAccessException) { diagnostic?.Invoke("抓包状态临时文件清理失败", error); }
        }
    }

    public void CloseSession()
    {
        context.Clear();
        sessionId = debugSession = null; counters.Clear();
    }
    public void Dispose() { try { SetRecording(false); } finally { CloseSession(); } }
}
